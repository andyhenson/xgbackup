//go:build linux

package vault

import (
	"fmt"
	"os"
	"strings"

	"github.com/xgbackup/xgbackup/internal/config"
)

const smbDropIn = "/etc/xgbackup/smb.conf"
const sambaConf = "/etc/samba/smb.conf"

// SyncSamba writes a per-client writable drop share and a read-only snapshot
// share. The operator still sets Samba passwords with smbpasswd. Reach the
// shares over the LAN, or over WireGuard when the path leaves the site.
func SyncSamba() error {
	if err := requireRoot(); err != nil {
		return err
	}
	cfg, err := config.Load(config.ConfigPath)
	if err != nil {
		return err
	}
	clients, err := ListClients(cfg.Pool)
	if err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("# generated by xgbackup smb sync\n")
	for _, name := range clients {
		fmt.Fprintf(&b, "\n[%s]\n", name)
		fmt.Fprintf(&b, "   path = %s\n", dropDir(cfg.Pool, name))
		b.WriteString("   browseable = yes\n")
		b.WriteString("   read only = no\n")
		fmt.Fprintf(&b, "   valid users = %s\n", name)
		fmt.Fprintf(&b, "   force user = %s\n", name)
	}
	readers := sambaReaders(cfg)
	b.WriteString("\n[xgbackup-snaps]\n")
	fmt.Fprintf(&b, "   path = %s\n", snapsRoot(cfg.Pool))
	b.WriteString("   browseable = yes\n")
	b.WriteString("   read only = yes\n")
	fmt.Fprintf(&b, "   valid users = %s\n", readers)
	if err := os.MkdirAll("/etc/xgbackup", 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(smbDropIn, []byte(b.String()), 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s\n", smbDropIn)
	if _, err := os.Stat(sambaConf); err != nil {
		fmt.Println("samba is not installed. Install it, then add this line to /etc/samba/smb.conf:")
		fmt.Printf("include = %s\n", smbDropIn)
	} else if err := ensureSambaInclude(); err != nil {
		return err
	}
	for _, name := range clients {
		fmt.Printf("set the samba password for %s with: smbpasswd -a %s\n", name, name)
	}
	if err := run("systemctl", "try-reload-or-restart", "smbd"); err != nil {
		fmt.Printf("smbd was not reloaded: %s\n", err)
	}
	return nil
}

func sambaReaders(cfg config.Config) string {
	names := []string{"root"}
	seen := map[string]bool{"root": true}
	add := func(name string) {
		if name == "" || seen[name] {
			return
		}
		seen[name] = true
		names = append(names, name)
	}
	for _, name := range cfg.SetupUsers {
		add(name)
	}
	for _, rule := range cfg.Restore {
		add(rule.User)
	}
	return strings.Join(names, ", ")
}

func ensureSambaInclude() error {
	data, err := os.ReadFile(sambaConf)
	if err != nil {
		return err
	}
	line := "include = " + smbDropIn
	if strings.Contains(string(data), line) {
		return nil
	}
	f, err := os.OpenFile(sambaConf, os.O_APPEND|os.O_WRONLY, 0o644)
	if err != nil {
		return err
	}
	defer f.Close()
	if len(data) > 0 && data[len(data)-1] != '\n' {
		if _, err := f.WriteString("\n"); err != nil {
			return err
		}
	}
	_, err = f.WriteString("\n" + line + "\n")
	return err
}
